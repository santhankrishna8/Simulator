// Compiles the example sketches and writes src/sim/prebuilt.generated.ts, so the
// examples run even where no compile service is configured.
//   ARDUINO_ROOT=/opt/arduino node compile-service/build-prebuilt.mjs
import { writeFile } from "node:fs/promises";
import { compile } from "./compile.mjs";
import { SKETCHES } from "../src/sim/sketches.mjs";

const out = {};
for (const [id, source] of Object.entries(SKETCHES)) {
  const r = await compile(source);
  if (!r.ok) {
    console.error(id, r.diagnostics);
    process.exit(1);
  }
  out[id] = r.hex;
  console.log(id, `${r.flash} bytes flash, ${r.ram} bytes RAM`);
}
const body = Object.entries(out)
  .map(([id, hex]) => `  ${JSON.stringify(id)}: ${JSON.stringify(hex)},`)
  .join("\n");
await writeFile(new URL("../src/sim/prebuilt.generated.ts", import.meta.url), `// Generated by compile-service/build-prebuilt.mjs. Do not edit.\nexport const PREBUILT: Record<string, string> = {\n${body}\n};\n`);
